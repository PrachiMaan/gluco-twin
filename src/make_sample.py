"""Store a tiny, committed sample of the generated data.

`data/` is gitignored except for `data/sample/`. This script keeps that sample
in sync with the full generated cohort: three patients, first day only.

Run:  python src/make_sample.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
SAMPLE = DATA / "sample"
N = 3
STEPS = 288  # one day


def main() -> None:
    ehr = pd.read_csv(DATA / "ehr.csv").head(N)
    SAMPLE.mkdir(parents=True, exist_ok=True)
    ehr.to_csv(SAMPLE / "ehr_sample.csv", index=False)

    with np.load(DATA / "cgm.npz") as z:
        arrays = {}
        for key in z.files:
            if z[key].ndim != 2:
                continue
            width = 1 if key == "sleep_hours" else STEPS
            arrays[key] = z[key][:N, :width].copy()
    np.savez_compressed(SAMPLE / "cgm_sample.npz", **arrays)

    (SAMPLE / "README.md").write_text(
        "# Sample data\n\n"
        "Three synthetic patients, first day only, cut from the full generated\n"
        "cohort by `python src/make_sample.py`. The full dataset is regenerated by\n"
        "`make data` and is not committed. See `docs/DATA_CARD.md` for every\n"
        "distribution assumption.\n\n"
        f"- `ehr_sample.csv`: {len(ehr)} rows, the same columns as `data/ehr.csv`\n"
        f"- `cgm_sample.npz`: {STEPS} steps at 5 minutes (24 hours) per patient\n"
        "  with glucose, heart rate, HRV, steps and sleep stage\n\n"
        "Glucose uses -1 for missing readings. HRV is stored in tenths of a\n"
        "millisecond (divide by 10).\n\n"
        f"Generator seed: {json.loads((DATA / 'manifest.json').read_text())['seed']}\n"
    )
    print(f"[sample] wrote {SAMPLE}/ehr_sample.csv and cgm_sample.npz ({N} patients, {STEPS} steps)")


if __name__ == "__main__":
    main()
