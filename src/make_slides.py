def add_text(slide, text, left, top, width, height, size, color=INK, bold=False, align=PP_ALIGN.LEFT, spacing=1.0):
    box = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    frame = box.text_frame
    frame.word_wrap = True
    frame.margin_left = 0
    frame.margin_right = 0
    frame.margin_top = 0
    frame.margin_bottom = 0
    lines = text.split("\n")
    for i, line in enumerate(lines):
        paragraph = frame.paragraphs[0] if i == 0 else frame.add_paragraph()
        paragraph.alignment = align
        paragraph.line_spacing = spacing
        run = paragraph.add_run()
        run.text = line
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.name = "Arial"
        run.font.color.rgb = RGBColor(*(int(c * 255) for c in color))
    return box


def rule(slide, top=1.62):
    shape = slide.shapes.add_shape(1, Inches(0.7), Inches(top), Inches(11.93), Pt(1))
    shape.fill.solid()
    shape.fill.fore_color.rgb = RGBColor(220, 216, 208)
    shape.line.fill.background()


def image_fit(slide, path: Path, left, top, width, height):
    from PIL import Image

    with Image.open(path) as img:
        iw, ih = img.size
    scale = min(width / iw, height / ih)
    w, h = iw * scale, ih * scale
    slide.shapes.add_picture(str(path), Inches(left + (width - w) / 2), Inches(top + (height - h) / 2), Inches(w), Inches(h))


def build_pptx() -> None:
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank = prs.slide_layouts[6]

    for index, spec in enumerate(SLIDES):
        slide = prs.slides.add_slide(blank)
        background = slide.background
        background.fill.solid()
        background.fill.fore_color.rgb = RGBColor(255, 255, 255)
        kind = spec["kind"]

        if kind == "title":
            add_text(slide, spec["eyebrow"], 0.9, 0.9, 11.6, 0.4, 13, MUTED)
            add_text(slide, spec["title"], 0.85, 1.7, 11.6, 1.6, 66, INK, bold=True)
            add_text(slide, spec["subtitle"], 0.9, 3.55, 10.4, 1.3, 27, INK, spacing=1.15)
            add_text(slide, spec["foot"], 0.9, 6.55, 11.6, 0.5, 14, MUTED)
        elif kind == "closing":
            add_text(slide, spec["title"], 0.85, 1.5, 11.6, 1.4, 66, INK, bold=True)
            add_text(slide, spec["subtitle"], 0.9, 3.1, 10.6, 1.2, 26, INK, spacing=1.15)
            add_text(slide, spec["foot"], 0.9, 6.4, 11.6, 0.6, 13, MUTED)
        else:
            add_text(slide, spec["title"], 0.7, 0.55, 11.9, 1.4, 36, INK, bold=True, spacing=1.05)
            rule(slide)
            if kind == "bullets":
                top = 1.8
                count = len(spec["bullets"])
                size = 22 if count > 4 else 25
                step = 0.88 if count > 4 else 1.05
                for bullet in spec["bullets"]:
                    add_text(slide, "•", 0.7, top, 0.4, 0.5, size, MUTED)
                    add_text(slide, bullet, 1.12, top, 11.3, step - 0.08, size, INK, spacing=1.1)
                    top += step
                if spec.get("foot"):
                    add_text(slide, spec["foot"], 0.7, 6.5, 11.9, 0.5, 13, MUTED)
            elif kind == "stats":
                top = 2.35
                for i, (value, label) in enumerate(spec["stats"]):
                    x = 0.7 + i * 3.05
                    add_text(slide, value, x, top, 2.9, 1.1, 52, INK, bold=True)
                    add_text(slide, label, x, top + 1.15, 2.9, 0.5, 17, MUTED)
                if spec.get("foot"):
                    add_text(slide, spec["foot"], 0.7, 5.9, 11.9, 0.8, 15, MUTED)
            elif kind == "label":
                add_text(slide, spec["big"], 0.8, 1.8, 11.8, 1.6, 30, INK, spacing=1.2)
                top = 3.75
                for bullet in spec["bullets"]:
                    add_text(slide, "•", 0.7, top, 0.4, 0.5, 22, MUTED)
                    add_text(slide, bullet, 1.12, top, 11.3, 0.7, 21, INK)
                    top += 0.75
            elif kind == "table":
                left, top = 0.7, 1.75
                widths = [2.55, 4.2, 1.7, 3.3]
                for j, name in enumerate(spec["header"]):
                    add_text(slide, name, left + sum(widths[:j]), top, widths[j], 0.5, 15, MUTED)
                y = top + 0.6
                for i, row in enumerate(spec["rows"]):
                    bold = i == spec.get("bold_row", -1)
                    for j, cell in enumerate(row):
                        add_text(slide, cell, left + sum(widths[:j]), y, widths[j], 0.6, 21, INK, bold=bold)
                    y += 0.78
                if spec.get("foot"):
                    add_text(slide, spec["foot"], 0.7, 6.4, 11.9, 0.5, 13, MUTED)
            elif kind == "image":
                image_fit(slide, spec["image"], 0.75, 1.65, 11.85, 4.55)
                add_text(slide, spec["caption"], 0.75, 6.35, 11.85, 0.8, 14, MUTED, spacing=1.1)
