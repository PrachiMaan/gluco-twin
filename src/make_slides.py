def wrap(text: str, width: int = 58) -> list[str]:
    words = text.split()
    lines, current = [], ""
    for word in words:
        candidate = f"{current} {word}".strip()
        if len(candidate) <= width:
            current = candidate
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def pdf_slide(spec: dict, index: int, total: int, fig) -> None:
    fig.patch.set_facecolor("white")
    fig.text(0.06, 0.94, "", fontsize=1)
    kind = spec["kind"]

    if kind == "title":
        fig.text(0.06, 0.80, spec["eyebrow"], fontsize=10, color=MUTED)
        fig.text(0.06, 0.63, spec["title"], fontsize=54, color=INK, weight="bold")
        fig.text(0.065, 0.44, "\n".join(wrap(spec["subtitle"], 70)), fontsize=20, color=INK, linespacing=1.3)
        fig.text(0.065, 0.12, spec["foot"], fontsize=11, color=MUTED)
        return

    if kind == "closing":
        fig.text(0.06, 0.66, spec["title"], fontsize=52, color=INK, weight="bold")
        fig.text(0.065, 0.45, "\n".join(wrap(spec["subtitle"], 70)), fontsize=19, color=INK, linespacing=1.3)
        fig.text(0.065, 0.12, spec["foot"], fontsize=10.5, color=MUTED)
        return

    fig.text(0.06, 0.90, spec["title"], fontsize=28, color=INK, weight="bold", va="top", linespacing=1.1)
    fig.add_artist(plt.Line2D([0.06, 0.94], [0.795, 0.795], color="#dcd8d0", lw=0.9))

    if kind == "bullets":
        y = 0.72
        for bullet in spec["bullets"]:
            lines = wrap(bullet, 62)
            fig.text(0.075, y, "•", fontsize=16, color=MUTED, va="top")
            for line in lines:
                fig.text(0.11, y, line, fontsize=18, color=INK, va="top")
                y -= 0.062
            y -= 0.045
        if spec.get("foot"):
            fig.text(0.06, 0.07, "\n".join(wrap(spec["foot"], 110)), fontsize=10, color=MUTED, linespacing=1.3)
    elif kind == "stats":
        for i, (value, label) in enumerate(spec["stats"]):
            x = 0.06 + i * 0.232
            fig.text(x, 0.55, value, fontsize=38, color=INK, weight="bold", va="center")
            fig.text(x, 0.44, label, fontsize=12, color=MUTED, va="center")
        if spec.get("foot"):
            fig.text(0.06, 0.16, "\n".join(wrap(spec["foot"], 105)), fontsize=11, color=MUTED, linespacing=1.3)
    elif kind == "label":
        for i, line in enumerate(spec["big"].split("\n")):
            fig.text(0.07, 0.66 - i * 0.09, line, fontsize=24, color=INK)
        y = 0.42
        for bullet in spec["bullets"]:
            fig.text(0.075, y, "•", fontsize=13, color=MUTED, va="top")
            fig.text(0.11, y, "\n".join(wrap(bullet, 85)), fontsize=14.5, color=INK, va="top", linespacing=1.25)
            y -= 0.12
    elif kind == "table":
        left = 0.06
        widths = [0.20, 0.33, 0.14, 0.23]
        y = 0.71
        for j, name in enumerate(spec["header"]):
            fig.text(left + sum(widths[:j]), y, name, fontsize=11, color=MUTED)
        y -= 0.08
        for i, row in enumerate(spec["rows"]):
            weight = "bold" if i == spec.get("bold_row", -1) else "normal"
            for j, cell in enumerate(row):
                fig.text(left + sum(widths[:j]), y, cell, fontsize=16, color=INK, weight=weight)
            y -= 0.10
        if spec.get("foot"):
            fig.text(0.06, 0.08, "\n".join(wrap(spec["foot"], 115)), fontsize=10, color=MUTED, linespacing=1.3)
    elif kind in ("image", "images"):
        paths = [spec["image"]] if kind == "image" else spec["images"]
        box_left, box_top, box_w, box_h = 0.05, 0.17, 0.90, 0.56
        if len(paths) == 2:
            box_w = 0.44
            for i, path in enumerate(paths):
                _draw_image(fig, path, box_left + i * 0.455, 0.20, box_w, 0.52)
        else:
            _draw_image(fig, paths[0], box_left, box_top, box_w, box_h)
        fig.text(0.06, 0.055, "\n".join(wrap(spec["caption"], 128)), fontsize=10, color=MUTED, va="bottom", linespacing=1.35)

    fig.text(0.94, 0.03, f"{index + 1} / {total}", fontsize=9, color=MUTED, ha="right")


def _draw_image(fig, path: Path, left, top, width, height) -> None:
    image = imread(path)
    ih, iw = image.shape[:2]
    aspect = iw / ih
    if width / height > aspect:
        h = height
        w = h * aspect
    else:
        w = width
        h = w / aspect
    ax = fig.add_axes([left + (width - w) / 2, top + (height - h) / 2, w, h])
    ax.imshow(image)
    ax.axis("off")


def build_pdf() -> None:
    total = len(SLIDES)
    with PdfPages(DOCS / "presentation.pdf") as pdf:
        for index, spec in enumerate(SLIDES):
            fig = plt.figure(figsize=(13.333, 7.5), facecolor="white")
            pdf_slide(spec, index, total, fig)
            pdf.savefig(fig, facecolor="white")
            plt.close(fig)
    print(f"[slides] wrote {DOCS / 'presentation.pdf'} ({total} slides)")


def main() -> None:
    DOCS.mkdir(exist_ok=True)
    build_pptx()
    build_pdf()
    print("[slides] plain white background, large type, one idea per slide")


if __name__ == "__main__":
    main()
